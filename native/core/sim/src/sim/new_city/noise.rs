/// The noise generator with a seed, a frequency, and an octave count.
#[derive(Clone, Copy, Debug)]
pub struct Noise {
    seed: i32,
    frequency: f32,
    octaves: i32,
    bounding: f32,
}

impl Noise {
    pub fn new(seed: i64, frequency: f64, octaves: i32) -> Self {
        let mut amplitude = GAIN;
        let mut fractal = 1.0_f32;

        for _ in 1..octaves {
            fractal += amplitude;
            amplitude *= GAIN;
        }

        Self {
            seed: seed as i32,
            frequency: frequency as f32,
            octaves,
            bounding: 1.0 / fractal,
        }
    }

    /// `FastNoiseLite.get_noise_2d`: about -1 through 1.
    pub fn get_2d(&self, x: f32, y: f32) -> f32 {
        let mut x = x * self.frequency;
        let mut y = y * self.frequency;

        // the OpenSimplex2 skew
        let f2 = 0.5 * (SQRT3 - 1.0);
        let t = (x + y) * f2;
        x += t;
        y += t;

        let mut seed = self.seed;
        let mut sum = 0.0;
        let mut amplitude = self.bounding;

        for _ in 0..self.octaves {
            let noise = open_simplex_2s(seed, x, y);
            seed = seed.wrapping_add(1);
            sum += noise * amplitude;

            // the weighted strength is 0, so this keeps the amplitude
            amplitude *= lerp(1.0, (noise + 1.0).min(2.0) * 0.5, 0.0);
            x *= LACUNARITY;
            y *= LACUNARITY;
            amplitude *= GAIN;
        }

        sum
    }
}

fn lerp(a: f32, b: f32, t: f32) -> f32 {
    a + t * (b - a)
}

fn fast_floor(value: f32) -> i32 {
    if value >= 0.0 { value as i32 } else { value as i32 - 1 }
}

fn hash(seed: i32, x_primed: i32, y_primed: i32) -> i32 {
    (seed ^ x_primed ^ y_primed).wrapping_mul(HASH_MULTIPLIER)
}

fn gradient(seed: i32, x_primed: i32, y_primed: i32, xd: f32, yd: f32) -> f32 {
    let value = hash(seed, x_primed, y_primed);
    let value = value ^ (value >> 15);
    let index = (value & (127 << 1)) as usize;

    xd * GRADIENTS_2D[index] + yd * GRADIENTS_2D[index | 1]
}

/// The contribution of one lattice point at `(x, y)` from the sample, or
/// `None` outside its radius. A sample without it keeps its exact value.
fn corner(seed: i32, x_primed: i32, y_primed: i32, x: f32, y: f32) -> Option<f32> {
    let a = (2.0 / 3.0) - x * x - y * y;

    (a > 0.0).then(|| (a * a) * (a * a) * gradient(seed, x_primed, y_primed, x, y))
}

fn add_corner(value: &mut f32, contribution: Option<f32>) {
    if let Some(contribution) = contribution {
        *value += contribution;
    }
}

fn open_simplex_2s(seed: i32, x: f32, y: f32) -> f32 {
    let g2 = (3.0 - SQRT3) / 6.0;
    let i = fast_floor(x);
    let j = fast_floor(y);
    let xi = x - i as f32;
    let yi = y - j as f32;

    let i = i.wrapping_mul(PRIME_X);
    let j = j.wrapping_mul(PRIME_Y);
    let i1 = i.wrapping_add(PRIME_X);
    let j1 = j.wrapping_add(PRIME_Y);

    let t = (xi + yi) * g2;
    let x0 = xi - t;
    let y0 = yi - t;

    let a0 = (2.0 / 3.0) - x0 * x0 - y0 * y0;
    let mut value = (a0 * a0) * (a0 * a0) * gradient(seed, i, j, x0, y0);

    let a1 = (2.0 * (1.0 - 2.0 * g2) * (1.0 / g2 - 2.0)) * t + ((-2.0 * (1.0 - 2.0 * g2) * (1.0 - 2.0 * g2)) + a0);
    let x1 = x0 - (1.0 - 2.0 * g2);
    let y1 = y0 - (1.0 - 2.0 * g2);
    value += (a1 * a1) * (a1 * a1) * gradient(seed, i1, j1, x1, y1);

    let xmyi = xi - yi;

    if t > g2 {
        if xi + xmyi > 1.0 {
            add_corner(
                &mut value,
                corner(
                    seed,
                    i.wrapping_add(PRIME_X << 1),
                    j.wrapping_add(PRIME_Y),
                    x0 + (3.0 * g2 - 2.0),
                    y0 + (3.0 * g2 - 1.0),
                ),
            );
        } else {
            add_corner(&mut value, corner(seed, i, j.wrapping_add(PRIME_Y), x0 + g2, y0 + (g2 - 1.0)));
        }

        if yi - xmyi > 1.0 {
            add_corner(
                &mut value,
                corner(
                    seed,
                    i.wrapping_add(PRIME_X),
                    j.wrapping_add(PRIME_Y << 1),
                    x0 + (3.0 * g2 - 1.0),
                    y0 + (3.0 * g2 - 2.0),
                ),
            );
        } else {
            add_corner(&mut value, corner(seed, i.wrapping_add(PRIME_X), j, x0 + (g2 - 1.0), y0 + g2));
        }
    } else {
        if xi + xmyi < 0.0 {
            add_corner(&mut value, corner(seed, i.wrapping_sub(PRIME_X), j, x0 + (1.0 - g2), y0 - g2));
        } else {
            add_corner(&mut value, corner(seed, i.wrapping_add(PRIME_X), j, x0 + (g2 - 1.0), y0 + g2));
        }

        if yi < xmyi {
            add_corner(&mut value, corner(seed, i, j.wrapping_sub(PRIME_Y), x0 - g2, y0 - (g2 - 1.0)));
        } else {
            add_corner(&mut value, corner(seed, i, j.wrapping_add(PRIME_Y), x0 + g2, y0 + (g2 - 1.0)));
        }
    }

    value * OPEN_SIMPLEX_SCALE
}
